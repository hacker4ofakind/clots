// Writes lib/phosphor-names.ts: the names of every Phosphor icon, so the icon picker can list and search them
// without loading the library, and a Clot's icon can be loaded by name on its own.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const root = path.dirname(require.resolve("@phosphor-icons/react/package.json"));
const names = fs
  .readdirSync(path.join(root, "dist/csr"))
  .filter((f) => f.endsWith(".es.js"))
  .map((f) => f.replace(".es.js", ""))
  .sort();
const out = `// Generated by scripts/gen-phosphor-names.mjs. Do not edit.\nexport const PHOSPHOR_NAMES: readonly string[] = ${JSON.stringify(names)};\n`;
fs.writeFileSync(path.join(import.meta.dirname, "../lib/phosphor-names.ts"), out);
console.log(`${names.length} icons`);
